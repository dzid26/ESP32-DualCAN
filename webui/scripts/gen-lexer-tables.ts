import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO } from '../tests/helpers/corpus.ts';
import {
  BERRY,
  SOURCE_LOCK,
  buildLexDump,
  hashBerryLexer,
  lexDumpSource,
} from './lexer-tools.ts';

function probeType(text: string): number {
  const result = lexDumpSource(text);
  if (result.status !== 0) {
    throw new Error(`lex_dump probe failed for ${JSON.stringify(text)}:\n${result.stderr}`);
  }
  const first = result.stdout.trim().split('\n')[0];
  if (!first) {
    throw new Error(`lex_dump probe returned no token for ${JSON.stringify(text)}`);
  }
  return Number(first.split('\t')[0]);
}

function hexDecode(value: string): string {
  return Buffer.from(value, 'hex').toString('utf8');
}

buildLexDump();

const header = readFileSync(join(BERRY, 'src/be_lexer.h'), 'utf8');
const enumBody = /typedef enum \{([\s\S]*?)\} btokentype;/.exec(header)?.[1] ?? '';
const enumNames = [...enumBody.matchAll(/\b(Opt[A-Za-z0-9]+|Key[A-Za-z0-9]+)\b/g)]
  .map(match => match[1]);

const source = readFileSync(join(BERRY, 'src/be_lexer.c'), 'utf8');
const arrayBody = /static const char\* const token_strings\[\] = \{([\s\S]*?)\};/.exec(source)?.[1] ?? '';
const strings = [...arrayBody.matchAll(/"((?:\\.|[^"\\])*)"/g)]
  .map(match => JSON.parse(`"${match[1]}"`));

const operatorNames = enumNames.filter(name => name.startsWith('Opt') && name !== 'OptWalrus');
const keywordNames = enumNames.filter(name => name.startsWith('Key'));
const prefix = 6; // NONE, EOS, ID, INT, REAL, STR
const expected = prefix + operatorNames.length + keywordNames.length + 1;
if (strings.length !== expected) {
  throw new Error(`unexpected token_strings shape: ${strings.length} entries, expected ${expected}`);
}
const operatorTexts = operatorNames.map((_, index) => strings[index + prefix]);
const walrus = strings[strings.length - 1];
if (walrus !== ':=') {
  throw new Error(`unexpected final token string: ${JSON.stringify(walrus)}`);
}
const keywords = [...new Set(keywordNames.map(name => name.slice(3).toLowerCase()))].sort();
const punctuation = [...new Set([...operatorTexts, walrus])].sort((a, b) => b.length - a.length);

const keywordTypes: Record<string, number> = {};
for (const text of keywords) keywordTypes[text] = probeType(text);

const punctuationTypes: Record<string, number> = {};
for (const text of punctuation) punctuationTypes[text] = probeType(text);

const simple: Record<string, string> = {};
const letters = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789?\\\'"';
for (const letter of letters) {
  const result = lexDumpSource('"' + '\\' + letter + '"');
  if (result.status !== 0) continue;
  const first = result.stdout.trim().split('\n')[0];
  if (!first) continue;
  const [type, value] = first.split('\t');
  if (Number(type) !== 5) continue;
  simple[letter] = hexDecode(value);
}

const lock = hashBerryLexer();
const content = [
  '// Generated by webui/scripts/gen-lexer-tables.ts. Do not edit.',
  `// Berry source: ${JSON.stringify(lock.files)}`,
  '',
  `export const KEYWORDS: ReadonlySet<string> = new Set(${JSON.stringify(keywords)});`,
  '',
  `export const KEYWORD_TYPES: Readonly<Record<string, number>> = ${JSON.stringify(keywordTypes, null, 2)};`,
  '',
  `export const PUNCTUATION: readonly string[] = ${JSON.stringify(punctuation)};`,
  '',
  `export const PUNCTUATION_TYPES: Readonly<Record<string, number>> = ${JSON.stringify(punctuationTypes, null, 2)};`,
  '',
  `export const SIMPLE_ESCAPES: Readonly<Record<string, string>> = ${JSON.stringify(simple, null, 2)};`,
  '',
].join('\n');

const tablePath = join(REPO, 'webui/src/lib/berry/lexer-tables.ts');
writeFileSync(tablePath, content);
writeFileSync(SOURCE_LOCK, `${JSON.stringify(lock, null, 2)}\n`);
console.log(`wrote ${keywords.length} keywords, ${punctuation.length} punctuation, ${Object.keys(simple).length} escapes`);
